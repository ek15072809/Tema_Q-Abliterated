# -*- coding: utf-8 -*-
"""書き出した非検閲化モデルの HuggingFace Hub へのアップロード。

モデル書き出し後に「HuggingFaceにアップロードするか」を尋ね、
リポジトリ名とAPIキーの入力からアップロードできる
(非対話環境では ``--hf-repo`` / ``--hf-token`` で指定)。

リポジトリ名はユーザー入力の末尾に ``-Tema_Q-Abliterated`` を強制的に
付与する (既に付いている場合は二重に付けない)。名前空間
(``username/repo``) が省略された場合は APIキーの所有者 (whoami) の
ユーザー名で補う。

アップロードには依存ライブラリ ``huggingface_hub`` (既に本体依存に含まれる)
を使い、``create_repo`` (exist_ok) + ``upload_folder`` で行う。
失敗してもパイプライン全体は失敗させず、ローカルの出力が残っている旨を
表示して続行する。
"""

from __future__ import annotations

import getpass
import re
import sys
from pathlib import Path
from typing import Any, Callable

from .msg import tr

# リポジトリ名に強制的に付与する接尾辞
REPO_SUFFIX = "-Tema_Q-Abliterated"

# リポジトリIDとして許容する形式 (namespace/repo-name または repo-name)
_REPO_ID_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*(/[A-Za-z0-9][A-Za-z0-9._-]*)?$")


def _is_interactive() -> bool:
    """対話的な入力が可能か (TTYかつ非quiet想定)。"""
    try:
        return bool(hasattr(sys.stdin, "isatty") and sys.stdin.isatty())
    except Exception:
        return False


def resolve_repo_id(raw: str, username: str | None = None) -> str:
    """ユーザー入力からアップロード先のリポジトリIDを決定する。

    - 末尾への ``-Tema_Q-Abliterated`` 付与は強制 (冪等: 既にあれば付けない)
    - ``username/repo`` 形式でなければ whoami のユーザー名で補う
    - 不正な文字は ValueError
    """
    name = (raw or "").strip().strip("/")
    if not name:
        raise ValueError(tr("hf_repo_empty"))
    if not _REPO_ID_RE.match(name):
        raise ValueError(tr("hf_repo_invalid", r=name))
    if "/" not in name:
        if not username:
            raise ValueError(tr("hf_repo_need_ns"))
        name = f"{username}/{name}"
    if not name.endswith(REPO_SUFFIX):
        name = name + REPO_SUFFIX
    return name


def _ask(prompt: str, secret: bool = False,
         input_fn: Callable[[str], str] | None = None) -> str:
    """1行入力。secret=Trueならgetpass (エコーバック抑制) を使う。"""
    if input_fn is not None:
        return input_fn(prompt).strip()
    if secret:
        try:
            return getpass.getpass(prompt).strip()
        except Exception:
            return input(prompt).strip()
    return input(prompt).strip()


def upload_model_folder(output_dir: Path, repo_id: str, token: str) -> str:
    """出力ディレクトリを HuggingFace Hub のモデルリポジトリへアップロードする。

    戻り値: リポジトリID。トークン不正・ネットワークエラー等は例外を投げる
    (呼び出し側がローカル出力の所在とともに表示する)。
    """
    from huggingface_hub import HfApi

    api = HfApi(token=token)
    # トークン検証 (不正ならここで例外)
    who = api.whoami()
    username = None
    if isinstance(who, dict):
        username = who.get("name") or (who.get("user") or {}).get("name")
    if "/" not in repo_id and username:
        repo_id = f"{username}/{repo_id.split('/')[-1]}"

    api.create_repo(repo_id=repo_id, repo_type="model", exist_ok=True,
                    private=False)
    api.upload_folder(
        folder_path=str(output_dir),
        repo_id=repo_id,
        repo_type="model",
        commit_message="Uncensored model generated by Tema_Q-Abliterated",
    )
    return repo_id


def maybe_upload(settings, output_dir: Path,
                 input_fn: Callable[[str], str] | None = None,
                 is_tty: bool | None = None) -> str | None:
    """モデル書き出し後のアップロード入口。

    優先順位:
      1. ``--hf-repo`` + ``--hf-token`` の両方が指定されていれば無確認でアップロード
      2. 対話環境なら「アップロードするか」を尋ね、リポジトリ名→APIキーの
         入力を経てアップロード
      3. それ以外 (非対話・未指定) はスキップを表示

    戻り値: アップロードしたリポジトリID (スキップ/失敗時は None)。
    この関数自体は例外を投げない (失敗は表示して None を返す)。
    """
    if is_tty is None:
        is_tty = input_fn is not None or _is_interactive()

    repo_input = (settings.hf_repo or "").strip()
    token = (settings.hf_token or "").strip()
    noninteractive_ready = bool(repo_input and token)

    if not noninteractive_ready:
        if not is_tty:
            print(tr("hf_skip_noninteractive"))
            return None
        ans = _ask(tr("hf_ask"), input_fn=input_fn)
        if ans.lower() not in ("y", "yes"):
            print(tr("hf_skip_declined"))
            return None
        # 対話入力で不足分を補う
        if not repo_input:
            repo_input = _ask(tr("hf_repo_prompt"), input_fn=input_fn)
        if not token:
            token = _ask(tr("hf_token_prompt"), secret=(input_fn is None),
                         input_fn=input_fn)

    try:
        print(tr("hf_uploading", r=repo_input))
        from huggingface_hub import HfApi
        api = HfApi(token=token)
        who = api.whoami()
        username = None
        if isinstance(who, dict):
            username = who.get("name") or (who.get("user") or {}).get("name")
        repo_id = resolve_repo_id(repo_input, username=username)
        print(tr("hf_repo_resolved", r=repo_id))
        repo_id = upload_model_folder(output_dir, repo_id, token)
        print(tr("hf_upload_done", r=repo_id))
        return repo_id
    except Exception as e:  # noqa: BLE001
        print(tr("hf_upload_fail", err=f"{type(e).__name__}: {e}", d=output_dir))
        return None
